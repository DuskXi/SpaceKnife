"""TypeScript declarations from JSON Schema: a plugin's ``web/sk-plugin.d.ts`` (``plugin build``).

Every ``$defs`` model becomes an interface (or a union type). Models reachable from what a client
sends (a method's params) are *inputs*: fields that are not required are optional. Every other model
is an *output*: the host always serialises every field, so all are present. ``tools/gen_ts_protocol.py``
uses the same functions for the core protocol's ``generated.ts``.
"""

from __future__ import annotations

import json
import re
from typing import Any

IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def refs_in(node: Any) -> set[str]:
    out: set[str] = set()
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "$ref" and isinstance(v, str):
                out.add(ref_name(v))
            else:
                out |= refs_in(v)
    elif isinstance(node, list):
        for v in node:
            out |= refs_in(v)
    return out


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return ref_name(node["$ref"])
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    if "enum" in node:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in node["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in node:
            parts = [ts_type(p) for p in node[key]]
            joiner = " & " if key == "allOf" else " | "
            uniq = list(dict.fromkeys(parts))
            return joiner.join(f"({p})" if " | " in p and joiner == " & " else p for p in uniq)
    t = node.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**node, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = node.get("items")
        if isinstance(items, dict) and items:
            inner = ts_type(items)
            return f"({inner})[]" if " | " in inner else f"{inner}[]"
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(p) for p in node["prefixItems"]) + "]"
        return "unknown[]"
    if t == "object" or "properties" in node:
        if "properties" in node:
            return (
                "{ "
                + "; ".join(
                    prop_line(k, v, k in node.get("required", []), True)
                    for k, v in node["properties"].items()
                )
                + " }"
            )
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def prop_line(name: str, node: dict[str, Any], required: bool, output: bool) -> str:
    key = name if IDENT.match(name) else json.dumps(name)
    optional = not required and not output  # outputs: the backend always serialises every field
    return f"{key}{'?' if optional else ''}: {ts_type(node)}"


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {ln}\n" for ln in lines) + f"{indent} */\n"


def input_models(defs: dict[str, Any], roots: list[str]) -> set[str]:
    """The models reachable from what clients send (``roots``): their optional fields stay optional."""
    inputs: set[str] = set()
    frontier = list(roots)
    while frontier:
        name = frontier.pop()
        if name in inputs or name not in defs:
            continue
        inputs.add(name)
        frontier.extend(refs_in(defs[name]))
    return inputs


def declarations(defs: dict[str, Any], inputs: set[str]) -> list[str]:
    """One interface (or type) per model, sorted by name."""
    out: list[str] = []
    for name in sorted(defs):
        node = defs[name]
        out.append(doc(node.get("description")))
        if "properties" in node:
            output = name not in inputs
            out.append(f"export interface {name} {{\n")
            required = set(node.get("required", []))
            for key, prop in node["properties"].items():
                out.append(doc(prop.get("description"), "  "))
                out.append(f"  {prop_line(key, prop, key in required, output)};\n")
            out.append("}\n\n")
        else:
            out.append(f"export type {name} = {ts_type(node)};\n\n")
    return out


PLUGIN_HEADER = "// Generated by spaceknife plugin build from the plugin's schema — do not edit by hand.\n"


def generate_plugin(schema: dict[str, Any]) -> str:
    """``web/sk-plugin.d.ts`` of one plugin: its models (named with its prefix, ``ExampleDupesFind…``),
    ``Methods`` / ``Events`` / ``States`` by local name, and ``sk`` typed with them.

    ``schema``: ``{"plugin": id, "methods": {name: {params, result, doc?}}, "events": {name:
    {payload, doc?}}, "states": {name: {payload, doc?}}, "$defs": {...}}`` (refs as in the core
    schema); a method without params takes ``Record<string, never>``."""
    defs: dict[str, Any] = schema.get("$defs", {})
    methods: dict[str, Any] = schema.get("methods", {})
    inputs = input_models(defs, [ref_name(m["params"]) for m in methods.values() if m.get("params")])
    out = [PLUGIN_HEADER, f"// Plugin {schema['plugin']}\n\n", 'import type { Sk } from "./_sk/sk";\n\n']
    out += declarations(defs, inputs)

    def ref_or(spec: dict[str, Any], key: str, default: str) -> str:
        return ref_name(spec[key]) if spec.get(key) else default

    # types, not interfaces: an object type has the index signature Sk<M extends Record<…>> wants
    out.append("export type Methods = {\n")
    for name, spec in sorted(methods.items()):
        out.append(doc(spec.get("doc"), "  "))
        params = ref_or(spec, "params", "Record<string, never>")
        out.append(f"  {name}: {{ params: {params}; result: {ref_or(spec, 'result', 'unknown')} }};\n")
    out.append("};\n\n")
    for title, key in (("Events", "events"), ("States", "states")):
        out.append(f"export type {title} = {{\n")
        for name, spec in sorted(schema.get(key, {}).items()):
            out.append(doc(spec.get("doc"), "  "))
            out.append(f"  {name}: {ref_or(spec, 'payload', 'unknown')};\n")
        out.append("};\n\n")
    out.append("declare const sk: Sk<Methods, Events, States>;\nexport default sk;\n")
    return "".join(out)


