//! TypeScript types for protocol v1, generated from [`crate::schema::export_schema`].
//!
//! Same output shape as the old `tools/gen_ts_protocol.py`: every `$defs` model becomes an
//! interface (or a union type); `Methods` and `Events` map each method / event name to its params,
//! result and payload types. Models reachable from a method's params are *inputs*: fields that are
//! not required are optional. Every other model is an *output*: the backend always serialises every
//! field, so all are present.
//!
//! Write it with `cargo run -p sk-protocol --bin gen-ts -- <out.ts>`.

use std::collections::BTreeSet;

use serde_json::{Map, Value};

use crate::schema::{export_schema, schema_hash};
use crate::{PROTOCOL_VERSION, SUBPROTOCOL, WS_PATH};

pub const HEADER: &str = "// Generated by `cargo run -p sk-protocol --bin gen-ts` from the Rust protocol types — do not edit by hand.\n";

fn ref_name(r: &str) -> &str {
    r.rsplit('/').next().unwrap_or(r)
}

fn refs_in(node: &Value, out: &mut BTreeSet<String>) {
    match node {
        Value::Object(m) => {
            for (k, v) in m {
                match (k.as_str(), v) {
                    ("$ref", Value::String(s)) => {
                        out.insert(ref_name(s).to_owned());
                    }
                    _ => refs_in(v, out),
                }
            }
        }
        Value::Array(a) => a.iter().for_each(|v| refs_in(v, out)),
        _ => {}
    }
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn dumps(v: &Value) -> String {
    serde_json::to_string(v).expect("json")
}

fn dedup(parts: Vec<String>) -> Vec<String> {
    let mut seen = Vec::with_capacity(parts.len());
    for p in parts {
        if !seen.contains(&p) {
            seen.push(p);
        }
    }
    seen
}

fn ts_type(node: &Value) -> String {
    let obj = match node {
        Value::Bool(true) => return "unknown".to_owned(),
        Value::Bool(false) => return "never".to_owned(),
        Value::Object(o) => o,
        _ => return "unknown".to_owned(),
    };
    if let Some(Value::String(r)) = obj.get("$ref") {
        return ref_name(r).to_owned();
    }
    if let Some(c) = obj.get("const") {
        return dumps(c);
    }
    if let Some(Value::Array(e)) = obj.get("enum") {
        return e.iter().map(dumps).collect::<Vec<_>>().join(" | ");
    }
    for key in ["anyOf", "oneOf", "allOf"] {
        if let Some(Value::Array(parts)) = obj.get(key) {
            let parts = dedup(parts.iter().map(ts_type).collect());
            if key == "allOf" {
                return parts
                    .iter()
                    .map(|p| {
                        if p.contains(" | ") {
                            format!("({p})")
                        } else {
                            p.clone()
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(" & ");
            }
            return parts.join(" | ");
        }
    }
    match obj.get("type") {
        Some(Value::Array(types)) => {
            let parts: Vec<String> = types
                .iter()
                .map(|t| {
                    let mut o = obj.clone();
                    o.insert("type".into(), t.clone());
                    ts_type(&Value::Object(o))
                })
                .collect();
            return dedup(parts).join(" | ");
        }
        Some(Value::String(t)) => match t.as_str() {
            "string" => return "string".into(),
            "integer" | "number" => return "number".into(),
            "boolean" => return "boolean".into(),
            "null" => return "null".into(),
            "array" => {
                if let Some(items) = obj.get("items")
                    && (items.as_object().is_some_and(|o| !o.is_empty()) || items.is_boolean())
                {
                    let inner = ts_type(items);
                    return if inner.contains(" | ") {
                        format!("({inner})[]")
                    } else {
                        format!("{inner}[]")
                    };
                }
                if let Some(Value::Array(p)) = obj.get("prefixItems") {
                    return format!("[{}]", p.iter().map(ts_type).collect::<Vec<_>>().join(", "));
                }
                return "unknown[]".into();
            }
            "object" => {}
            _ => return "unknown".into(),
        },
        _ => {}
    }
    if obj.get("type").and_then(Value::as_str) == Some("object") || obj.contains_key("properties") {
        if let Some(Value::Object(props)) = obj.get("properties") {
            let required = required_of(obj);
            let mut keys: Vec<&String> = props.keys().collect();
            keys.sort();
            let fields: Vec<String> = keys
                .into_iter()
                .map(|k| prop_line(k, &props[k], required.contains(k.as_str()), true))
                .collect();
            return format!("{{ {} }}", fields.join("; "));
        }
        return match obj.get("additionalProperties") {
            Some(extra @ Value::Object(o)) if !o.is_empty() => {
                format!("Record<string, {}>", ts_type(extra))
            }
            _ => "Record<string, unknown>".into(),
        };
    }
    "unknown".into()
}

fn required_of(obj: &Map<String, Value>) -> BTreeSet<&str> {
    obj.get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default()
}

fn prop_line(name: &str, node: &Value, required: bool, output: bool) -> String {
    let key = if is_ident(name) {
        name.to_owned()
    } else {
        dumps(&Value::String(name.to_owned()))
    };
    let optional = !required && !output; // outputs: the backend always serialises every field
    format!(
        "{key}{}: {}",
        if optional { "?" } else { "" },
        ts_type(node)
    )
}

fn doc(text: Option<&str>, indent: &str) -> String {
    let Some(text) = text.map(str::trim).filter(|t| !t.is_empty()) else {
        return String::new();
    };
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() == 1 {
        return format!("{indent}/** {} */\n", lines[0]);
    }
    let mut out = format!("{indent}/**\n");
    for ln in lines {
        if ln.is_empty() {
            out.push_str(&format!("{indent} *\n"));
        } else {
            out.push_str(&format!("{indent} * {ln}\n"));
        }
    }
    out.push_str(&format!("{indent} */\n"));
    out
}

fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

/// The whole `generated.ts` text.
pub fn generate() -> String {
    generate_from(&export_schema(), schema_hash())
}

/// The TypeScript for a schema document produced by [`export_schema`].
pub fn generate_from(schema: &Value, hash: &str) -> String {
    let empty = Map::new();
    let defs = schema["$defs"].as_object().unwrap_or(&empty);
    let methods = schema["methods"].as_object().unwrap_or(&empty);
    let notifications = schema["notifications"].as_object().unwrap_or(&empty);
    let events = schema["events"].as_object().unwrap_or(&empty);

    let mut inputs: BTreeSet<String> = BTreeSet::new();
    let mut frontier: Vec<String> = methods
        .values()
        .chain(notifications.values())
        .map(|m| ref_name(str_of(m, "params")).to_owned())
        .collect();
    while let Some(name) = frontier.pop() {
        if inputs.contains(&name) {
            continue;
        }
        let Some(def) = defs.get(&name) else { continue };
        inputs.insert(name);
        let mut found = BTreeSet::new();
        refs_in(def, &mut found);
        frontier.extend(found);
    }

    let mut out = String::with_capacity(96 * 1024);
    out.push_str(HEADER);
    out.push_str("/* eslint-disable */\n\n");
    out.push_str(&format!(
        "export const PROTOCOL_VERSION = {};\n",
        dumps(&Value::String(PROTOCOL_VERSION.into()))
    ));
    out.push_str(&format!(
        "export const SUBPROTOCOL = {};\n",
        dumps(&Value::String(SUBPROTOCOL.into()))
    ));
    out.push_str(&format!(
        "export const WS_PATH = {};\n",
        dumps(&Value::String(WS_PATH.into()))
    ));
    out.push_str(&format!(
        "export const SCHEMA_HASH = {};\n\n",
        dumps(&Value::String(hash.into()))
    ));

    let mut names: Vec<&String> = defs.keys().collect();
    names.sort();
    for name in names {
        let node = &defs[name];
        out.push_str(&doc(node.get("description").and_then(Value::as_str), ""));
        let obj = node.as_object();
        let props = obj
            .and_then(|o| o.get("properties"))
            .and_then(Value::as_object);
        let is_struct = obj.is_some_and(|o| {
            o.get("type").and_then(Value::as_str) == Some("object")
                && !o
                    .get("additionalProperties")
                    .is_some_and(|a| a.is_object() && !a.as_object().unwrap().is_empty())
        });
        if props.is_some() || is_struct {
            let output = !inputs.contains(name.as_str());
            out.push_str(&format!("export interface {name} {{\n"));
            if let Some(props) = props {
                let required = required_of(obj.expect("object"));
                let mut keys: Vec<&String> = props.keys().collect();
                keys.sort();
                for key in keys {
                    let prop = &props[key];
                    out.push_str(&doc(prop.get("description").and_then(Value::as_str), "  "));
                    out.push_str(&format!(
                        "  {};\n",
                        prop_line(key, prop, required.contains(key.as_str()), output)
                    ));
                }
            }
            out.push_str("}\n\n");
        } else {
            out.push_str(&format!("export type {name} = {};\n\n", ts_type(node)));
        }
    }

    out.push_str("export interface Methods {\n");
    let mut mnames: Vec<&String> = methods.keys().collect();
    mnames.sort();
    for name in mnames {
        let spec = &methods[name];
        out.push_str(&doc(spec.get("doc").and_then(Value::as_str), "  "));
        let params = ref_name(str_of(spec, "params"));
        let result = ref_name(str_of(spec, "result"));
        out.push_str(&format!(
            "  {}: {{ params: {params}; result: {result} }};\n",
            dumps(&Value::String(name.clone()))
        ));
    }
    out.push_str("}\n\nexport type MethodName = keyof Methods;\n\n");
    out.push_str("export interface Events {\n");
    let mut enames: Vec<&String> = events.keys().collect();
    enames.sort();
    for name in enames {
        let spec = &events[name];
        out.push_str(&doc(spec.get("doc").and_then(Value::as_str), "  "));
        out.push_str(&format!(
            "  {}: {};\n",
            dumps(&Value::String(name.clone())),
            ref_name(str_of(spec, "payload"))
        ));
    }
    out.push_str("}\n\nexport type EventName = keyof Events;\n");
    out
}
