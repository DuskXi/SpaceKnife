// Compile the design tokens and icons into what the desktop app (apps/desktop, alias @design) and the
// website read. Was tools/gen_design.py; same inputs, same CSS / TS / SVG output byte for byte.
//
// Source of truth (hand-edited):
//   design/tokens/*.tokens.json   DTCG-style tokens ($value / $type / $description, "{alias}" refs):
//                                 the dark theme, the base every theme starts from
//   design/tokens/themes/<theme>.tokens.json
//                                 a theme's overrides: the same paths with other values, colours and
//                                 shadows only, $type unchanged ("set + theme modifier", as in the
//                                 DTCG resolver module). Aliases resolve after the merge, so a token
//                                 that points at an overridden one follows it.
//   design/icons/icons.json       16×16 stroke icons (inner SVG markup)
//
// Generated (never edit by hand; CI runs --check):
//   design/build/tokens.css       CSS custom properties: light on :root, dark through
//                                 prefers-color-scheme or data-theme
//   design/build/tokens.ts        typed constants, every theme's tree (WebGL / canvas palettes)
//   design/build/icons/*.svg, design/build/icons.ts   icons
//
// (The QML, XAML and Python token outputs served the suspended Qt / WinUI clients and are gone.)
//
//   node tools/gen_design.mjs          # regenerate
//   node tools/gen_design.mjs --check  # exit 1 if any artefact is stale

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_DIR = join(ROOT, "design", "tokens");
export const THEMES_SUBDIR = "themes";
export const ICONS_JSON = join(ROOT, "design", "icons", "icons.json");
export const BUILD = join(ROOT, "design", "build");

const HEADER = "Generated by tools/gen_design.mjs from design/tokens — do not edit by hand.";
export const ALIAS = /^\{([A-Za-z0-9_.]+)\}$/;
const HEX = /^#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/;
const GENERIC_FAMILIES = new Set(["serif", "sans-serif", "monospace", "system-ui", "ui-monospace", "ui-sans-serif", "cursive"]);
// the base files hold the dark theme; every other theme overrides some of its colours and shadows
export const THEMES = ["dark", "light"];
export const BASE_THEME = "dark";
export const THEMED_TYPES = new Set(["color", "shadow"]);
const SUPPORTED_TYPES = new Set(["color", "dimension", "duration", "number", "fontWeight", "fontFamily", "cubicBezier", "shadow"]);

export class TokenError extends Error {}

const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const show = (v) => JSON.stringify(v);

// --------------------------------------------------------------------------- loading

export function loadTree(directory = TOKENS_DIR) {
  const files = existsSync(directory) ? readdirSync(directory).filter((n) => n.endsWith(".tokens.json")).sort() : [];
  if (!files.length) throw new TokenError(`no *.tokens.json files in ${directory}`);
  const tree = {};
  for (const file of files) {
    for (const [key, value] of Object.entries(readJson(join(directory, file)))) {
      if (key.startsWith("$")) continue;
      if (Object.hasOwn(tree, key)) throw new TokenError(`top-level group '${key}' defined twice (second time in ${file})`);
      tree[key] = value;
    }
  }
  return tree;
}

/** Flatten the tree into Map(dotted path -> [type, raw value, description]). */
export function collect(tree) {
  const out = new Map();
  const walk = (node, path, inherited) => {
    if (!isObj(node)) throw new TokenError(`${path.join(".")}: expected an object`);
    const typ = node.$type ?? inherited;
    if (Object.hasOwn(node, "$value")) {
      if (typ == null) throw new TokenError(`${path.join(".")}: token has no $type (set it on the token or a parent group)`);
      if (!SUPPORTED_TYPES.has(typ)) throw new TokenError(`${path.join(".")}: unsupported $type '${typ}'`);
      out.set(path.join("."), [typ, node.$value, node.$description ?? null]);
      return;
    }
    for (const [key, child] of Object.entries(node)) if (!key.startsWith("$")) walk(child, [...path, key], typ);
  };
  for (const [key, node] of Object.entries(tree)) walk(node, [key], null);
  return out;
}

function num(value, where) {
  if (typeof value !== "number") throw new TokenError(`${where}: expected a number, got ${show(value)}`);
  return value;
}

function unit(value, u, where) {
  if (typeof value === "number") return value;
  if (!isObj(value) || value.unit !== u) throw new TokenError(`${where}: expected {'value': n, 'unit': '${u}'}, got ${show(value)}`);
  return num(value.value, where);
}

export function normalise(typ, value, where) {
  switch (typ) {
    case "color":
      if (typeof value !== "string" || !HEX.test(value)) throw new TokenError(`${where}: colors must be #RRGGBB or #RRGGBBAA, got ${show(value)}`);
      return value.toUpperCase();
    case "dimension":
      return unit(value, "px", where);
    case "duration":
      return unit(value, "ms", where);
    case "number":
    case "fontWeight":
      return num(value, where);
    case "fontFamily": {
      const families = typeof value === "string" ? [value] : value;
      if (!Array.isArray(families) || !families.length || !families.every((f) => typeof f === "string")) {
        throw new TokenError(`${where}: fontFamily must be a string or a non-empty list of strings`);
      }
      return families;
    }
    case "cubicBezier":
      if (!Array.isArray(value) || value.length !== 4) throw new TokenError(`${where}: cubicBezier must be [x1, y1, x2, y2]`);
      return value.map((v) => num(v, where));
    case "shadow":
      return (Array.isArray(value) ? value : [value]).map((layer) => {
        if (!isObj(layer)) throw new TokenError(`${where}: shadow layers must be objects`);
        return {
          color: normalise("color", layer.color, where),
          offsetX: unit(layer.offsetX ?? 0, "px", where),
          offsetY: unit(layer.offsetY ?? 0, "px", where),
          blur: unit(layer.blur ?? 0, "px", where),
          spread: unit(layer.spread ?? 0, "px", where),
        };
      });
  }
  throw new TokenError(`${where}: unsupported $type '${typ}'`);
}

/** Resolve the aliases: [{path, dotted, type, value, description}] in the order of `raw`. */
export function resolveTokens(raw) {
  const resolved = new Map();
  const valueOf = (name, stack = []) => {
    if (!resolved.has(name)) {
      const [typ, value] = raw.get(name);
      resolved.set(name, normalise(typ, deref(value, [...stack, name]), name));
    }
    return resolved.get(name);
  };
  const deref = (value, stack) => {
    if (typeof value === "string") {
      const m = ALIAS.exec(value);
      if (!m) return value;
      const target = m[1];
      if (stack.includes(target)) throw new TokenError(`alias cycle: ${[...stack, target].join(" -> ")}`);
      if (!raw.has(target)) throw new TokenError(`${stack.at(-1)}: unknown alias {${target}}`);
      return valueOf(target, stack);
    }
    if (Array.isArray(value)) return value.map((v) => deref(v, stack));
    if (isObj(value)) return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, deref(v, stack)]));
    return value;
  };
  return [...raw].map(([name, [typ, , desc]]) => ({ path: name.split("."), dotted: name, type: typ, value: valueOf(name), description: desc }));
}

/** Dotted paths of the tokens in a (partial) tree. */
export function tokenPaths(tree, path = []) {
  const out = [];
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith("$") || !isObj(node)) continue;
    if (Object.hasOwn(node, "$value")) out.push([...path, key].join("."));
    else out.push(...tokenPaths(node, [...path, key]));
  }
  return out;
}

/** `base` with the tokens of `override` in their places (new objects; neither argument changes). */
export function overlay(base, override, path = []) {
  const out = { ...base };
  for (const [key, node] of Object.entries(override)) {
    const where = [...path, key].join(".");
    if (key.startsWith("$")) {
      if (key === "$description") out[key] = node;
      else if (key === "$type" && node !== base.$type) throw new TokenError(`${path.join(".") || "(root)"}: a theme cannot change $type`);
      continue;
    }
    if (!Object.hasOwn(base, key)) throw new TokenError(`${where}: not in the base tokens (a theme only overrides existing tokens)`);
    const under = base[key];
    if (!isObj(node) || !isObj(under) || Object.hasOwn(node, "$value") !== Object.hasOwn(under, "$value")) {
      throw new TokenError(`${where}: a theme must replace a token with a token and a group with a group`);
    }
    if (Object.hasOwn(node, "$value")) {
      const picked = Object.fromEntries(Object.entries(node).filter(([k]) => ["$value", "$type", "$description"].includes(k)));
      out[key] = { ...under, ...picked };
    } else {
      out[key] = overlay(under, node, [...path, key]);
    }
  }
  return out;
}

/** The token tree of `theme`: the base files with the theme's overrides merged in. */
export function themeTree(directory = TOKENS_DIR, theme = BASE_THEME) {
  if (!THEMES.includes(theme)) throw new TokenError(`unknown theme '${theme}' (one of ${THEMES.join(", ")})`);
  const base = loadTree(directory);
  if (theme === BASE_THEME) return base;
  const file = join(directory, THEMES_SUBDIR, `${theme}.tokens.json`);
  if (!existsSync(file)) throw new TokenError(`theme '${theme}': ${file} not found`);
  const override = Object.fromEntries(Object.entries(readJson(file)).filter(([k]) => !k.startsWith("$")));
  const tree = overlay(base, override);
  const before = collect(base);
  const after = collect(tree);
  for (const name of tokenPaths(override)) {
    if (after.get(name)[0] !== before.get(name)[0]) throw new TokenError(`${name}: a theme cannot change $type (${before.get(name)[0]} -> ${after.get(name)[0]})`);
    if (!THEMED_TYPES.has(before.get(name)[0])) throw new TokenError(`${name}: a theme overrides only color and shadow tokens, not ${before.get(name)[0]}`);
  }
  return tree;
}

// Python's tuple order: element by element, a shorter prefix first
function comparePaths(a, b) {
  for (let i = 0; i < Math.min(a.length, b.length); i++) {
    if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  }
  return a.length - b.length;
}

export function loadTokens(directory = TOKENS_DIR, theme = BASE_THEME) {
  return resolveTokens(collect(themeTree(directory, theme))).sort((a, b) => comparePaths(a.path, b.path));
}

/** Every theme's tokens, the base theme first; all of them have the same paths and types. */
export function loadThemes(directory = TOKENS_DIR) {
  const themes = Object.fromEntries(THEMES.map((name) => [name, loadTokens(directory, name)]));
  const shape = (tokens) => tokens.map((t) => `${t.dotted}:${t.type}`).join("\n");
  for (const [name, tokens] of Object.entries(themes)) {
    if (shape(tokens) !== shape(themes[BASE_THEME])) throw new TokenError(`theme '${name}' does not have the base tokens' paths and types`);
  }
  return themes;
}

/** Dotted paths whose resolved value differs between the themes. */
export function themed(themes) {
  const values = Object.values(themes).map((tokens) => new Map(tokens.map((t) => [t.dotted, JSON.stringify(t.value)])));
  return new Set([...values[0]].filter(([name, v]) => values.slice(1).some((m) => m.get(name) !== v)).map(([name]) => name));
}

// --------------------------------------------------------------------------- naming

function words(path) {
  return path.flatMap((part) => part.split(/(?<=[a-z0-9])(?=[A-Z])|[^A-Za-z0-9]+/).filter(Boolean));
}
export const kebab = (path) => words(path).map((w) => w.toLowerCase()).join("-");
export const camel = (path) => {
  const w = words(path);
  return w[0].toLowerCase() + w.slice(1).map((x) => x[0].toUpperCase() + x.slice(1)).join("");
};
export const pascal = (path) => words(path).map((x) => x[0].toUpperCase() + x.slice(1)).join("");

// Python's str(int) / repr(float)
function fmt(n) {
  return Number.isInteger(n) ? String(n) : String(n);
}

export function cssValue(token) {
  const v = token.value;
  switch (token.type) {
    case "color":
      return v;
    case "dimension":
      return `${fmt(v)}px`;
    case "duration":
      return `${fmt(v)}ms`;
    case "number":
    case "fontWeight":
      return fmt(v);
    case "fontFamily":
      return v.map((f) => (GENERIC_FAMILIES.has(f) ? f : `"${f}"`)).join(", ");
    case "cubicBezier":
      return `cubic-bezier(${v.map(fmt).join(", ")})`;
    case "shadow":
      return v.map((s) => `${fmt(s.offsetX)}px ${fmt(s.offsetY)}px ${fmt(s.blur)}px ${fmt(s.spread)}px ${s.color}`).join(", ");
  }
  throw new TokenError(token.dotted);
}

// --------------------------------------------------------------------------- JSON as Python's json.dumps(indent=2, ensure_ascii=False)

/** Like JSON.stringify(value, null, 2), but a Map keeps its key order (numeric keys too). */
export function dumps(value, indent = "") {
  const inner = `${indent}  `;
  if (value instanceof Map) {
    if (!value.size) return "{}";
    return `{\n${[...value].map(([k, v]) => `${inner}${JSON.stringify(k)}: ${dumps(v, inner)}`).join(",\n")}\n${indent}}`;
  }
  if (Array.isArray(value)) {
    if (!value.length) return "[]";
    return `[\n${value.map((v) => `${inner}${dumps(v, inner)}`).join(",\n")}\n${indent}]`;
  }
  if (isObj(value)) return dumps(new Map(Object.entries(value)), indent);
  return JSON.stringify(value);
}

// --------------------------------------------------------------------------- emitters

export const cssDeclarations = (tokens) => tokens.map((t) => `--sk-${kebab(t.path)}: ${cssValue(t)};`);

/** Light on :root (so a page that knows nothing else starts light); dark when the system asks for
 * it (prefers-color-scheme) unless the page says data-theme="light", or anywhere data-theme="dark".
 * The theme blocks hold only what differs. */
export function emitCss(themes) {
  const varying = themed(themes);
  const block = (selector, scheme, tokens, indent = "") => [
    `${indent}${selector} {`,
    ...[`color-scheme: ${scheme};`, ...cssDeclarations(tokens)].map((line) => `${indent}  ${line}`),
    `${indent}}`,
  ];
  const dark = themes.dark.filter((t) => varying.has(t.dotted));
  const light = themes.light.filter((t) => varying.has(t.dotted));
  const lines = [`/* ${HEADER} */`, ...block(":root", "light", themes.light)];
  lines.push("@media (prefers-color-scheme: dark) {", ...block(':root:not([data-theme="light"])', "dark", dark, "  "), "}");
  lines.push(...block('[data-theme="dark"]', "dark", dark));
  lines.push(...block('[data-theme="light"]', "light", light));
  return `${lines.join("\n")}\n`;
}

function nested(tokens, leaf) {
  const root = new Map();
  for (const t of tokens) {
    let node = root;
    for (const part of t.path.slice(0, -1)) {
      if (!node.has(part)) node.set(part, new Map());
      node = node.get(part);
    }
    node.set(t.path.at(-1), leaf(t));
  }
  return root;
}

const tsLeaf = (t) => (t.type === "shadow" ? cssValue(t) : t.value);

export function emitTs(themes) {
  const tokens = themes[BASE_THEME];
  const body = dumps(nested(tokens, tsLeaf));
  const others = Object.entries(themes)
    .filter(([name]) => name !== BASE_THEME)
    .map(([name, theme]) => `  ${name}: ${dumps(nested(theme, tsLeaf)).replaceAll("\n", "\n  ")},\n`)
    .join("");
  const cssMap = dumps(new Map(tokens.map((t) => [t.dotted, `var(--sk-${kebab(t.path)})`])));
  const names = Object.keys(themes).map((n) => `"${n}"`).join(" | ");
  return (
    `// ${HEADER}\n\n` +
    `/** The ${BASE_THEME} theme (the base files). Colours follow the theme through \`themes\`. */\n` +
    `export const tokens = ${body} as const;\n\n` +
    "export type Tokens = typeof tokens;\n\n" +
    `export type ThemeName = ${names};\n\n` +
    "type Widen<T> = T extends string\n" +
    "  ? string\n" +
    "  : T extends number\n" +
    "    ? number\n" +
    "    : T extends readonly (infer U)[]\n" +
    "      ? readonly Widen<U>[]\n" +
    "      : { readonly [K in keyof T]: Widen<T[K]> };\n\n" +
    "/** A theme's tokens: the shape of `tokens` with any value. */\n" +
    "export type Theme = Widen<Tokens>;\n\n" +
    "/** Every theme's tokens (each a whole tree: a key missing or extra fails to compile). */\n" +
    "export const themes: Readonly<Record<ThemeName, Theme>> = {\n" +
    `  ${BASE_THEME}: tokens,\n` +
    others +
    "};\n\n" +
    "/** CSS custom property reference for each token, e.g. cssVar['color.bg.window']. */\n" +
    `export const cssVar = ${cssMap} as const;\n`
  );
}

// --------------------------------------------------------------------------- icons

export function loadIcons(path = ICONS_JSON) {
  const data = readJson(path);
  const icons = new Map(Object.entries(data.icons).map(([name, spec]) => [name, spec.svg]));
  for (const [name, inner] of icons) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(name)) throw new TokenError(`icon name '${name}' must be camelCase`);
    const lower = inner.toLowerCase();
    if (lower.includes("<script") || lower.includes("<style")) throw new TokenError(`icon '${name}' must not contain script/style`);
  }
  return [data, icons];
}

export function svgDocument(meta, inner) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="${meta.viewBox}" fill="none" ` +
    `stroke="currentColor" stroke-width="${meta.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>\n`
  );
}

export function emitIconsTs(meta, icons) {
  return (
    "// Generated by tools/gen_design.mjs from design/icons/icons.json — do not edit by hand.\n\n" +
    `export const iconViewBox = "${meta.viewBox}";\n` +
    `export const iconStrokeWidth = ${meta.strokeWidth};\n\n` +
    `export const icons = ${dumps(icons)} as const;\n\n` +
    "export type IconName = keyof typeof icons;\n"
  );
}

// --------------------------------------------------------------------------- driver

/** Map(absolute path -> text) of every generated file. */
export function artefacts() {
  const themes = loadThemes();
  const [meta, icons] = loadIcons();
  const files = new Map([
    [join(BUILD, "tokens.css"), emitCss(themes)],
    [join(BUILD, "tokens.ts"), emitTs(themes)],
    [join(BUILD, "icons.ts"), emitIconsTs(meta, icons)],
  ]);
  for (const [name, inner] of icons) files.set(join(BUILD, "icons", `${kebab([name])}.svg`), svgDocument(meta, inner));
  return files;
}

const iconFiles = () => {
  const dir = join(BUILD, "icons");
  return existsSync(dir) ? readdirSync(dir).filter((n) => n.endsWith(".svg")).map((n) => join(dir, n)) : [];
};

/** The generated files that are missing or differ, and stray icons. */
export function stale(files) {
  const out = [...files].filter(([p, text]) => !existsSync(p) || readFileSync(p, "utf8") !== text).map(([p]) => p);
  return [...out, ...iconFiles().filter((p) => !files.has(p))];
}

function main(argv) {
  let files;
  try {
    files = artefacts();
  } catch (e) {
    if (!(e instanceof TokenError)) throw e;
    console.error(`error: ${e.message}`);
    return 2;
  }
  if (argv.includes("--check")) {
    const bad = stale(files);
    for (const p of bad) console.error(`stale: ${relative(ROOT, p).replaceAll("\\", "/")}`);
    if (bad.length) console.error("run: node tools/gen_design.mjs");
    return bad.length ? 1 : 0;
  }
  for (const orphan of iconFiles()) if (!files.has(orphan)) rmSync(orphan);
  for (const [p, text] of files) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  console.log(`wrote ${files.size} files`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
