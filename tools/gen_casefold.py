"""The case folding of `sk_protocol::filter_syntax::casefold`, generated from Python 3.12.

0.3.x compared class names and aliases, filter class spellings and export names with Python's
`str.casefold` (Python 3.12: Unicode 15.0.0). The Rust backend must fold exactly the same, or a
class table 0.3.4 accepted is refused (and replaced by the built-in one), and a spelling 0.3.4
found names nothing. `str.casefold` maps every code point on its own (no context), so a table of
the code points it changes is all there is to it.

Writes, from this Python's `str.casefold`:

* crates/sk-protocol/src/casefold_table.rs: every non-ASCII code point it changes, sorted (ASCII is
  folded in code);
* crates/sk-protocol/tests/data/casefold_python312.txt: every code point it changes, ASCII too,
  which `tests/casefold.rs` compares the Rust function with over all of Unicode.

    python3.12 -I tools/gen_casefold.py           # rewrite both
    python3.12 -I tools/gen_casefold.py --check   # exit 1 when either is stale
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "crates" / "sk-protocol" / "src" / "casefold_table.rs"
DATA = ROOT / "crates" / "sk-protocol" / "tests" / "data" / "casefold_python312.txt"
UNICODE = "15.0.0"


def folds() -> list[tuple[int, str]]:
    out = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue  # no Rust string holds a surrogate
        s = chr(c)
        f = s.casefold()
        if f != s:
            out.append((c, f))
    return out


def rust_str(s: str) -> str:
    return "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else f"\\u{{{ord(ch):x}}}" for ch in s)


def table(pairs: list[tuple[int, str]]) -> str:
    lines = [
        "// Generated by tools/gen_casefold.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}'s str.casefold (Unicode {UNICODE}); do not edit.",
        "",
        "/// Every non-ASCII code point `str.casefold` changes, sorted, with what it becomes.",
        "pub(crate) static FOLDS: &[(u32, &str)] = &[",
    ]
    lines += [f'    (0x{c:04X}, "{rust_str(f)}"),' for c, f in pairs if c >= 0x80]
    lines.append("];")
    return "\n".join(lines) + "\n"


def data(pairs: list[tuple[int, str]]) -> str:
    lines = [
        f"# str.casefold of Python {sys.version_info.major}.{sys.version_info.minor} (Unicode {UNICODE}), "
        "every code point it changes: code point; what it becomes (code points). Generated by tools/gen_casefold.py.",
    ]
    lines += [f"{c:04X}; {' '.join(f'{ord(ch):04X}' for ch in f)}" for c, f in pairs]
    return "\n".join(lines) + "\n"


def main() -> int:
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != UNICODE:
        print(f"needs Python 3.12 (Unicode {UNICODE}), the one 0.3.x shipped; this is {sys.version}", file=sys.stderr)
        return 2
    pairs = folds()
    want = {TABLE: table(pairs), DATA: data(pairs)}
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
