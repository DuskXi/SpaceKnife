"""Compile design tokens and icons into artefacts for all three frontends.

Source of truth (hand-edited):
    design/tokens/*.tokens.json   DTCG-style tokens ($value / $type / $description, "{alias}" refs)
    design/icons/icons.json       16×16 stroke icons (inner SVG markup)

Generated (never edit by hand; CI runs ``--check``):
    design/build/tokens.css                          Electron (CSS custom properties)
    design/build/tokens.ts                           Electron (typed constants, WebGL palette)
    design/build/qml/SpaceKnife/Tokens/Tokens.qml    Qt (QML singleton) + qmldir
    design/build/xaml/Tokens.xaml                    WinUI3 (ResourceDictionary)
    packages/client/src/spaceknife_client/tokens.py  Python frontends (Qt/WinUI view layer)
    design/build/icons/*.svg, design/build/icons.ts  icons

Usage::

    uv run python tools/gen_design.py          # regenerate
    uv run python tools/gen_design.py --check  # exit 1 if any artefact is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TOKENS_DIR = ROOT / "design" / "tokens"
ICONS_JSON = ROOT / "design" / "icons" / "icons.json"
BUILD = ROOT / "design" / "build"
PY_OUT = ROOT / "packages" / "client" / "src" / "spaceknife_client" / "tokens.py"

HEADER = "Generated by tools/gen_design.py from design/tokens — do not edit by hand."
ALIAS = re.compile(r"^\{([A-Za-z0-9_.]+)\}$")
HEX = re.compile(r"^#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")
GENERIC_FAMILIES = {
    "serif",
    "sans-serif",
    "monospace",
    "system-ui",
    "ui-monospace",
    "ui-sans-serif",
    "cursive",
}
SUPPORTED_TYPES = {
    "color",
    "dimension",
    "duration",
    "number",
    "fontWeight",
    "fontFamily",
    "cubicBezier",
    "shadow",
}


class TokenError(ValueError):
    pass


@dataclass(frozen=True, slots=True)
class Token:
    path: tuple[str, ...]
    type: str
    value: Any
    description: str | None = None

    @property
    def dotted(self) -> str:
        return ".".join(self.path)


# --------------------------------------------------------------------------- loading


def load_tree(directory: Path = TOKENS_DIR) -> dict[str, Any]:
    tree: dict[str, Any] = {}
    files = sorted(directory.glob("*.tokens.json"))
    if not files:
        raise TokenError(f"no *.tokens.json files in {directory}")
    for file in files:
        data = json.loads(file.read_text(encoding="utf-8"))
        for key, value in data.items():
            if key.startswith("$"):
                continue
            if key in tree:
                raise TokenError(f"top-level group {key!r} defined twice (second time in {file.name})")
            tree[key] = value
    return tree


def collect(tree: dict[str, Any]) -> dict[str, tuple[str, Any, str | None]]:
    """Flatten the tree into ``dotted path -> (type, raw value, description)``."""
    out: dict[str, tuple[str, Any, str | None]] = {}

    def walk(node: Any, path: tuple[str, ...], inherited: str | None) -> None:
        if not isinstance(node, dict):
            raise TokenError(f"{'.'.join(path)}: expected an object")
        typ = node.get("$type", inherited)
        if "$value" in node:
            if typ is None:
                raise TokenError(
                    f"{'.'.join(path)}: token has no $type (set it on the token or a parent group)"
                )
            if typ not in SUPPORTED_TYPES:
                raise TokenError(f"{'.'.join(path)}: unsupported $type {typ!r}")
            out[".".join(path)] = (typ, node["$value"], node.get("$description"))
            return
        for key, child in node.items():
            if not key.startswith("$"):
                walk(child, (*path, key), typ)

    for key, node in tree.items():
        walk(node, (key,), None)
    return out


def resolve(raw: dict[str, tuple[str, Any, str | None]]) -> list[Token]:
    resolved: dict[str, Any] = {}

    def deref(value: Any, stack: tuple[str, ...]) -> Any:
        if isinstance(value, str):
            match = ALIAS.match(value)
            if match:
                target = match.group(1)
                if target in stack:
                    raise TokenError(f"alias cycle: {' -> '.join((*stack, target))}")
                if target not in raw:
                    raise TokenError(f"{stack[-1]}: unknown alias {{{target}}}")
                return value_of(target, stack)
            return value
        if isinstance(value, list):
            return [deref(v, stack) for v in value]
        if isinstance(value, dict):
            return {k: deref(v, stack) for k, v in value.items()}
        return value

    def value_of(name: str, stack: tuple[str, ...] = ()) -> Any:
        if name not in resolved:
            typ, value, _ = raw[name]
            resolved[name] = normalise(typ, deref(value, (*stack, name)), name)
        return resolved[name]

    return [Token(tuple(name.split(".")), typ, value_of(name), desc) for name, (typ, _, desc) in raw.items()]


def _num(value: Any, where: str) -> float | int:
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise TokenError(f"{where}: expected a number, got {value!r}")
    return value


def _unit(value: Any, unit: str, where: str) -> float | int:
    if isinstance(value, int | float) and not isinstance(value, bool):
        return value
    if not isinstance(value, dict) or value.get("unit") != unit:
        raise TokenError(f"{where}: expected {{'value': n, 'unit': '{unit}'}}, got {value!r}")
    return _num(value.get("value"), where)


def normalise(typ: str, value: Any, where: str) -> Any:
    if typ == "color":
        if not isinstance(value, str) or not HEX.match(value):
            raise TokenError(f"{where}: colors must be #RRGGBB or #RRGGBBAA, got {value!r}")
        return value.upper()
    if typ == "dimension":
        return _unit(value, "px", where)
    if typ == "duration":
        return _unit(value, "ms", where)
    if typ in ("number", "fontWeight"):
        return _num(value, where)
    if typ == "fontFamily":
        families = [value] if isinstance(value, str) else value
        if not isinstance(families, list) or not families or not all(isinstance(f, str) for f in families):
            raise TokenError(f"{where}: fontFamily must be a string or a non-empty list of strings")
        return tuple(families)
    if typ == "cubicBezier":
        if not isinstance(value, list) or len(value) != 4:
            raise TokenError(f"{where}: cubicBezier must be [x1, y1, x2, y2]")
        return tuple(_num(v, where) for v in value)
    if typ == "shadow":
        layers = value if isinstance(value, list) else [value]
        out = []
        for layer in layers:
            if not isinstance(layer, dict):
                raise TokenError(f"{where}: shadow layers must be objects")
            out.append(
                {
                    "color": normalise("color", layer.get("color"), where),
                    "offsetX": _unit(layer.get("offsetX", 0), "px", where),
                    "offsetY": _unit(layer.get("offsetY", 0), "px", where),
                    "blur": _unit(layer.get("blur", 0), "px", where),
                    "spread": _unit(layer.get("spread", 0), "px", where),
                }
            )
        return tuple(out)
    raise TokenError(f"{where}: unsupported $type {typ!r}")


def load_tokens(directory: Path = TOKENS_DIR) -> list[Token]:
    return sorted(resolve(collect(load_tree(directory))), key=lambda t: t.path)


# --------------------------------------------------------------------------- naming


def _words(path: tuple[str, ...]) -> list[str]:
    words: list[str] = []
    for part in path:
        words += [w for w in re.split(r"(?<=[a-z0-9])(?=[A-Z])|[^A-Za-z0-9]+", part) if w]
    return words


def kebab(path: tuple[str, ...]) -> str:
    return "-".join(w.lower() for w in _words(path))


def camel(path: tuple[str, ...]) -> str:
    words = _words(path)
    return words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])


def pascal(path: tuple[str, ...]) -> str:
    return "".join(w[:1].upper() + w[1:] for w in _words(path))


def argb(color: str) -> str:
    """#RRGGBB[AA] -> #AARRGGBB (Qt and XAML order)."""
    rgb, alpha = color[1:7], color[7:9] or "FF"
    return f"#{alpha}{rgb}"


def _fmt(n: float | int) -> str:
    return str(int(n)) if float(n).is_integer() else repr(float(n))


def css_value(token: Token) -> str:
    v = token.value
    match token.type:
        case "color":
            return str(v)
        case "dimension":
            return f"{_fmt(v)}px"
        case "duration":
            return f"{_fmt(v)}ms"
        case "number" | "fontWeight":
            return _fmt(v)
        case "fontFamily":
            return ", ".join(f if f in GENERIC_FAMILIES else f'"{f}"' for f in v)
        case "cubicBezier":
            return f"cubic-bezier({', '.join(_fmt(x) for x in v)})"
        case "shadow":
            layers = []
            for s in v:
                x, y, blur, spread = (_fmt(s[k]) for k in ("offsetX", "offsetY", "blur", "spread"))
                layers.append(f"{x}px {y}px {blur}px {spread}px {s['color']}")
            return ", ".join(layers)
    raise TokenError(token.dotted)


# --------------------------------------------------------------------------- emitters


def emit_css(tokens: list[Token]) -> str:
    lines = [f"/* {HEADER} */", ":root {"]
    lines += [f"  --sk-{kebab(t.path)}: {css_value(t)};" for t in tokens]
    lines.append("}")
    return "\n".join(lines) + "\n"


def _nested(tokens: list[Token], leaf: Any) -> dict[str, Any]:
    root: dict[str, Any] = {}
    for t in tokens:
        node = root
        for part in t.path[:-1]:
            node = node.setdefault(part, {})
        node[t.path[-1]] = leaf(t)
    return root


def _ts_leaf(t: Token) -> Any:
    if t.type in ("fontFamily", "cubicBezier"):
        return list(t.value)
    if t.type == "shadow":
        return css_value(t)
    return t.value


def emit_ts(tokens: list[Token]) -> str:
    body = json.dumps(_nested(tokens, _ts_leaf), indent=2, ensure_ascii=False)
    css_map = json.dumps(
        {t.dotted: f"var(--sk-{kebab(t.path)})" for t in tokens}, indent=2, ensure_ascii=False
    )
    return (
        f"// {HEADER}\n\n"
        f"export const tokens = {body} as const;\n\n"
        "export type Tokens = typeof tokens;\n\n"
        "/** CSS custom property reference for each token, e.g. cssVar['color.bg.window']. */\n"
        f"export const cssVar = {css_map} as const;\n"
    )


def emit_qml(tokens: list[Token]) -> str:
    lines = [f"// {HEADER}", "pragma Singleton", "import QtQuick", "", "QtObject {"]
    for t in tokens:
        name = camel(t.path)
        v = t.value
        match t.type:
            case "color":
                lines.append(f'    readonly property color {name}: "{argb(v)}"')
            case "dimension" | "number":
                lines.append(f"    readonly property real {name}: {_fmt(v)}")
            case "duration" | "fontWeight":
                lines.append(f"    readonly property int {name}: {int(v)}")
            case "fontFamily":
                lines.append(f'    readonly property string {name}: "{v[0]}"')
                lines.append(
                    f"    readonly property var {name}Stack: {json.dumps(list(v), ensure_ascii=False)}"
                )
            case "cubicBezier":
                lines.append(f"    readonly property var {name}: [{', '.join(_fmt(x) for x in v)}]")
            case "shadow":
                lines.append(f"    // {name}: shadows are drawn per component in QML (see tokens.ts)")
    lines.append("}")
    return "\n".join(lines) + "\n"


QMLDIR = "module SpaceKnife.Tokens\nsingleton Tokens 1.0 Tokens.qml\n"


def _xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def emit_xaml(tokens: list[Token]) -> str:
    lines = [
        f"<!-- {HEADER} -->",
        "<ResourceDictionary",
        '    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    ]
    for t in tokens:
        key = "Sk" + pascal(t.path)
        v = t.value
        match t.type:
            case "color":
                lines.append(f'    <Color x:Key="{key}">{argb(v)}</Color>')
                lines.append(f'    <SolidColorBrush x:Key="{key}Brush" Color="{argb(v)}"/>')
            case "dimension" | "number":
                lines.append(f'    <x:Double x:Key="{key}">{_fmt(v)}</x:Double>')
            case "fontWeight":
                lines.append(f'    <x:Int32 x:Key="{key}">{int(v)}</x:Int32>')
            case "duration":
                lines.append(f'    <x:Double x:Key="{key}Ms">{_fmt(v)}</x:Double>')
            case "fontFamily":
                lines.append(f'    <FontFamily x:Key="{key}">{_xml(", ".join(v))}</FontFamily>')
            case "cubicBezier":
                lines.append(f'    <x:String x:Key="{key}">{",".join(_fmt(x) for x in v)}</x:String>')
            case "shadow":
                lines.append(f'    <x:String x:Key="{key}Css">{_xml(css_value(t))}</x:String>')
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


def _py_literal(t: Token) -> str:
    v = t.value
    if t.type == "shadow":
        return repr(css_value(t))
    if t.type in ("fontFamily", "cubicBezier"):
        return "(" + ", ".join(repr(x) for x in v) + ("," if len(v) == 1 else "") + ")"
    return repr(v)


def emit_py(tokens: list[Token]) -> str:
    entries = "\n".join(f"    {t.dotted!r}: {_py_literal(t)}," for t in tokens)
    return (
        f'"""{HEADER}\n\n'
        "Flat dotted-path → value map for the Python frontends (Qt, WinUI3). Colors are\n"
        "'#RRGGBB[AA]' strings, dimensions are px, durations are ms, shadows are CSS strings.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "from collections.abc import Mapping\n"
        "from typing import Final\n\n"
        "TokenValue = str | int | float | tuple[str, ...] | tuple[float, ...]\n\n"
        f"TOKENS: Final[Mapping[str, TokenValue]] = {{\n{entries}\n}}\n\n\n"
        "def token(path: str) -> TokenValue:\n"
        '    """Value of the token at ``path`` (e.g. ``"color.bg.window"``)."""\n'
        "    return TOKENS[path]\n"
    )


# --------------------------------------------------------------------------- icons


def load_icons(path: Path = ICONS_JSON) -> tuple[dict[str, Any], dict[str, str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    icons = {name: spec["svg"] for name, spec in data["icons"].items()}
    for name, inner in icons.items():
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*", name):
            raise TokenError(f"icon name {name!r} must be camelCase")
        if "<script" in inner.lower() or "<style" in inner.lower():
            raise TokenError(f"icon {name!r} must not contain script/style")
    return data, icons


def svg_document(meta: dict[str, Any], inner: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" '
        f'viewBox="{meta["viewBox"]}" fill="none" stroke="currentColor" '
        f'stroke-width="{meta["strokeWidth"]}" stroke-linecap="round" stroke-linejoin="round">'
        f"{inner}</svg>\n"
    )


def emit_icons_ts(meta: dict[str, Any], icons: dict[str, str]) -> str:
    body = json.dumps(icons, indent=2, ensure_ascii=False)
    return (
        "// Generated by tools/gen_design.py from design/icons/icons.json — do not edit by hand.\n\n"
        f'export const iconViewBox = "{meta["viewBox"]}";\n'
        f"export const iconStrokeWidth = {meta['strokeWidth']};\n\n"
        f"export const icons = {body} as const;\n\n"
        "export type IconName = keyof typeof icons;\n"
    )


# --------------------------------------------------------------------------- driver


def artefacts() -> dict[Path, str]:
    tokens = load_tokens()
    meta, icons = load_icons()
    files: dict[Path, str] = {
        BUILD / "tokens.css": emit_css(tokens),
        BUILD / "tokens.ts": emit_ts(tokens),
        BUILD / "qml" / "SpaceKnife" / "Tokens" / "Tokens.qml": emit_qml(tokens),
        BUILD / "qml" / "SpaceKnife" / "Tokens" / "qmldir": QMLDIR,
        BUILD / "xaml" / "Tokens.xaml": emit_xaml(tokens),
        BUILD / "icons.ts": emit_icons_ts(meta, icons),
        PY_OUT: emit_py(tokens),
    }
    for name, inner in icons.items():
        files[BUILD / "icons" / f"{kebab((name,))}.svg"] = svg_document(meta, inner)
    return files


def stale(files: dict[Path, str]) -> list[Path]:
    out = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    icon_dir = BUILD / "icons"
    if icon_dir.exists():
        out += [p for p in icon_dir.glob("*.svg") if p not in files]
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if generated files are out of date")
    args = parser.parse_args(argv)
    try:
        files = artefacts()
    except TokenError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if args.check:
        bad = stale(files)
        for path in bad:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if bad:
            print("run: uv run python tools/gen_design.py", file=sys.stderr)
        return 1 if bad else 0
    icon_dir = BUILD / "icons"
    if icon_dir.exists():
        for orphan in icon_dir.glob("*.svg"):
            if orphan not in files:
                orphan.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
