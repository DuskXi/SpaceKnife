"""Generate TypeScript types for protocol v1 from ``packages/protocol/schema/protocol.schema.json``.

    uv run python tools/gen_ts_protocol.py           # write
    uv run python tools/gen_ts_protocol.py --check   # exit 1 if the output is stale (CI)

Every ``$defs`` model becomes an interface (or a union type); ``Methods`` and ``Events`` map
each method / event name to its params, result and payload types so the Electron client is fully
typed. Models reachable from a method's params are *inputs*: fields that are not required are
optional. Every other model is an *output*: the backend always serialises every field (defaults
and default factories included), so all are present.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "packages" / "protocol" / "schema" / "protocol.schema.json"
OUT = ROOT / "apps" / "electron" / "src" / "renderer" / "src" / "protocol" / "generated.ts"
HEADER = "// Generated by tools/gen_ts_protocol.py from protocol.schema.json — do not edit by hand.\n"
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def refs_in(node: Any) -> set[str]:
    out: set[str] = set()
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "$ref" and isinstance(v, str):
                out.add(ref_name(v))
            else:
                out |= refs_in(v)
    elif isinstance(node, list):
        for v in node:
            out |= refs_in(v)
    return out


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return ref_name(node["$ref"])
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    if "enum" in node:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in node["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in node:
            parts = [ts_type(p) for p in node[key]]
            joiner = " & " if key == "allOf" else " | "
            uniq = list(dict.fromkeys(parts))
            return joiner.join(f"({p})" if " | " in p and joiner == " & " else p for p in uniq)
    t = node.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**node, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = node.get("items")
        if isinstance(items, dict) and items:
            inner = ts_type(items)
            return f"({inner})[]" if " | " in inner else f"{inner}[]"
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(p) for p in node["prefixItems"]) + "]"
        return "unknown[]"
    if t == "object" or "properties" in node:
        if "properties" in node:
            return (
                "{ "
                + "; ".join(
                    prop_line(k, v, k in node.get("required", []), True)
                    for k, v in node["properties"].items()
                )
                + " }"
            )
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def prop_line(name: str, node: dict[str, Any], required: bool, output: bool) -> str:
    key = name if IDENT.match(name) else json.dumps(name)
    optional = not required and not output  # outputs: the backend always serialises every field
    return f"{key}{'?' if optional else ''}: {ts_type(node)}"


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {ln}\n" for ln in lines) + f"{indent} */\n"


def generate(schema: dict[str, Any]) -> str:
    defs: dict[str, Any] = schema["$defs"]
    inputs: set[str] = set()
    frontier = [ref_name(m["params"]) for m in schema["methods"].values()]
    frontier += [ref_name(m["params"]) for m in schema.get("notifications", {}).values()]
    while frontier:
        name = frontier.pop()
        if name in inputs or name not in defs:
            continue
        inputs.add(name)
        frontier.extend(refs_in(defs[name]))
    out = [HEADER, "/* eslint-disable */\n\n"]
    from spaceknife_protocol import SUBPROTOCOL, WS_PATH
    from spaceknife_protocol.schema import schema_hash

    out.append(f"export const PROTOCOL_VERSION = {json.dumps(schema['protocol'])};\n")
    out.append(f"export const SUBPROTOCOL = {json.dumps(SUBPROTOCOL)};\n")
    out.append(f"export const WS_PATH = {json.dumps(WS_PATH)};\n")
    out.append(f"export const SCHEMA_HASH = {json.dumps(schema_hash())};\n\n")
    for name in sorted(defs):
        node = defs[name]
        out.append(doc(node.get("description")))
        if "properties" in node:
            output = name not in inputs
            out.append(f"export interface {name} {{\n")
            required = set(node.get("required", []))
            for key, prop in node["properties"].items():
                out.append(doc(prop.get("description"), "  "))
                out.append(f"  {prop_line(key, prop, key in required, output)};\n")
            out.append("}\n\n")
        else:
            out.append(f"export type {name} = {ts_type(node)};\n\n")
    out.append("export interface Methods {\n")
    for name, spec in sorted(schema["methods"].items()):
        out.append(doc(spec.get("doc"), "  "))
        params, result = ref_name(spec["params"]), ref_name(spec["result"])
        out.append(f"  {json.dumps(name)}: {{ params: {params}; result: {result} }};\n")
    out.append("}\n\nexport type MethodName = keyof Methods;\n\n")
    out.append("export interface Events {\n")
    for name, spec in sorted(schema["events"].items()):
        out.append(doc(spec.get("doc"), "  "))
        out.append(f"  {json.dumps(name)}: {ref_name(spec['payload'])};\n")
    out.append("}\n\nexport type EventName = keyof Events;\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    text = generate(schema)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_ts_protocol.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(schema['$defs'])} types, {len(schema['methods'])} methods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
